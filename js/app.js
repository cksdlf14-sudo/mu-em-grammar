function splitChapters(md) {
  const parts = md.split(/(?=^## Ch\d+\.)/m);
  const chapters = [];
  for (const part of parts) {
    const m = part.match(/^## (Ch\d+)\.\s*(.+?)$/m);
    if (m) {
      chapters.push({
        num: parseInt(m[1].replace('Ch', '')),
        title: m[2].trim(),
        body: part.trim()
      });
    }
  }
  return chapters.sort((a, b) => a.num - b.num);
}
 
